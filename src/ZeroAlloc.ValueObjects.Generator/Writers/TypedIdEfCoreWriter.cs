using System.Collections.Generic;
using System.Text;
using ZeroAlloc.ValueObjects.Generator.Models;

namespace ZeroAlloc.ValueObjects.Generator.Writers;

// Emits the EF Core registration of [TypedId] structs, for a compilation that references
// ZeroAlloc.ValueObjects.EfCore. Every type is named at compile time, so the registration needs no
// reflection and no assembly scan, and is trim-safe and NativeAOT-safe, unlike
// TypedIdModelConfigurationExtensions.AddTypedIdConventions, which scans an assembly at run time.
internal static class TypedIdEfCoreWriter
{
    // No hint name of a typed ID contains "-T": Sanitize writes an escape as "-u".
    public const string ConventionsHintName = "ZeroAlloc-TypedIdConventions.EfCore.g.cs";

    private const string Builder = "global::Microsoft.EntityFrameworkCore.ModelConfigurationBuilder";
    private const string Converter = "global::ZeroAlloc.ValueObjects.EfCore.TypedIdValueConverter";

    /// <summary>
    /// The hint name of the file that adds <c>AddTypedIdConvention</c> to a struct:
    /// <c>App.OrderId.TypedId.EfCore.g.cs</c> for <c>App.OrderId.TypedId.g.cs</c>.
    /// </summary>
    public static string MemberHintName(string typedIdHintName) =>
        typedIdHintName.Substring(0, typedIdHintName.Length - ".g.cs".Length) + ".EfCore.g.cs";

    /// <summary>
    /// A partial part of the struct with a static <c>AddTypedIdConvention</c> method, which
    /// registers <c>TypedIdValueConverter&lt;TId, TBacking&gt;</c> for every property of the struct's
    /// type. It is a member of the struct, so it can be called wherever the struct can be named,
    /// from inside its containing type for a private nested struct.
    /// </summary>
    public static string WriteMember(TypedIdModel model)
    {
        var name = TypeDeclarations.Identifier(model.Name);
        var guid = model.Backing == 1;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        if (model.Namespace is not null)
        {
            sb.AppendLine($"namespace {model.Namespace};");
            sb.AppendLine();
        }

        foreach (var containing in model.ContainingTypes)
        {
            sb.AppendLine(containing);
            sb.AppendLine("{");
        }

        sb.AppendLine($"{model.Accessibility} readonly partial record struct {name}");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine($"    /// Registers <c>TypedIdValueConverter&lt;{name}, {(guid ? "Guid" : "long")}&gt;</c> as the value converter of every");
        sb.AppendLine($"    /// <c>{name}</c> property in the model, nullable ones included, so EF Core stores it as its");
        sb.AppendLine($"    /// <c>{(guid ? "Guid" : "long")}</c> value. Call it from <c>DbContext.ConfigureConventions</c>. It names every type");
        sb.AppendLine("    /// at compile time and needs no reflection or assembly scan, so it is trim-safe and NativeAOT-safe.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    /// <param name=\"builder\">The builder passed to <c>DbContext.ConfigureConventions</c>.</param>");
        sb.AppendLine("    /// <returns><paramref name=\"builder\"/>, so calls can be chained.</returns>");
        sb.AppendLine($"    public static {Builder} AddTypedIdConvention({Builder} builder)");
        sb.AppendLine("    {");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(builder);");
        sb.AppendLine($"        builder.Properties<{name}>().HaveConversion<{Converter}<{name}, {(guid ? "global::System.Guid" : "long")}>>();");
        sb.AppendLine("        return builder;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        for (var i = 0; i < model.ContainingTypes.Count; i++) sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// An extension class with <c>Add{Assembly}TypedIdConventions</c>, which calls the
    /// <c>AddTypedIdConvention</c> of every struct in <paramref name="typeNames"/>. The assembly name is
    /// part of both names, so the classes that two assemblies generate never clash in a third.
    /// </summary>
    /// <param name="assemblyName">The name of the compilation's assembly.</param>
    /// <param name="accessibility">The keyword of the class and method: <c>public</c> or <c>internal</c>.</param>
    /// <param name="typeNames">The fully qualified names of the structs, sorted.</param>
    public static string WriteConventions(string assemblyName, string accessibility, IReadOnlyList<string> typeNames)
    {
        var stem = IdentifierStem(assemblyName);
        var className = (char.IsDigit(stem[0]) ? "_" : string.Empty) + stem + "TypedIdModelConfigurationExtensions";
        var methodName = "Add" + stem + "TypedIdConventions";
        var assembly = Escape(assemblyName);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace Microsoft.EntityFrameworkCore;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Registers the EF Core value converters of the [TypedId] structs declared in {assembly},");
        sb.AppendLine("/// without reflection or an assembly scan.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"{accessibility} static class {className}");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Registers <c>TypedIdValueConverter&lt;TId, TBacking&gt;</c> for every [TypedId] struct declared in");
        sb.AppendLine($"    /// {assembly}, so EF Core stores each as its <c>Guid</c> or <c>long</c> value. Call it from");
        sb.AppendLine("    /// <c>DbContext.ConfigureConventions</c>. It names every type at compile time and needs no");
        sb.AppendLine("    /// reflection or assembly scan, so it is trim-safe and NativeAOT-safe.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    /// <remarks>");
        sb.AppendLine("    /// A struct that is private, protected or private protected, or nested in such a type, cannot be");
        sb.AppendLine("    /// named here and is left out. Register it with its own <c>AddTypedIdConvention</c>, called from");
        sb.AppendLine("    /// inside its containing type.");
        sb.AppendLine("    /// </remarks>");
        sb.AppendLine("    /// <param name=\"builder\">The builder passed to <c>DbContext.ConfigureConventions</c>.</param>");
        sb.AppendLine("    /// <returns><paramref name=\"builder\"/>, so calls can be chained.</returns>");
        sb.AppendLine($"    {accessibility} static {Builder} {methodName}(this {Builder} builder)");
        sb.AppendLine("    {");
        sb.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(builder);");
        foreach (var typeName in typeNames)
        {
            sb.AppendLine($"        {typeName}.AddTypedIdConvention(builder);");
        }
        sb.AppendLine("        return builder;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    // The assembly name without the characters an identifier cannot hold, as ZeroAlloc.Inject
    // derives its Add{Assembly}Services name: Shop.Domain gives ShopDomain.
    private static string IdentifierStem(string assemblyName)
    {
        var sb = new StringBuilder(assemblyName.Length);
        foreach (var c in assemblyName)
        {
            if (char.IsLetterOrDigit(c)) sb.Append(c);
        }
        return sb.Length == 0 ? "Assembly" : sb.ToString();
    }

    private static string Escape(string text) =>
        text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
